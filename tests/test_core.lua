test('defaults al primer login', function()
    KnuJunkDB = nil; FAKE.Fire('ADDON_LOADED', 'KnuJunk')
    eq(ns.DB.enabled, true)
    eq(ns.DB.show.coin, true)
    eq(type(ns.DB.overrides), 'table')
end)
test('respeta DB existente', function()
    KnuJunkDB = { enabled = false }; FAKE.Fire('ADDON_LOADED', 'KnuJunk')
    eq(ns.DB.enabled, false)
    eq(ns.DB.show.hammer, true)
end)
test('ignora el ADDON_LOADED de otros addons', function()
    KnuJunkDB = nil; ns.DB = nil; FAKE.Fire('ADDON_LOADED', 'OtroAddon')
    eq(KnuJunkDB, nil); eq(ns.DB, nil)
end)
test('la DB no comparte tablas con los defaults', function()
    KnuJunkDB = nil; FAKE.Fire('ADDON_LOADED', 'KnuJunk')
    ns.DB.show.coin = false; ns.DB.overrides[123] = 'junk'
    eq(ns.Defaults.show.coin, true); eq(next(ns.Defaults.overrides), nil)
end)
test('OnLogin corre al PLAYER_LOGIN y de inmediato si ya pasó', function()
    local calls = 0
    ns.OnLogin(function() calls = calls + 1 end)
    eq(calls, 0)
    FAKE.Fire('PLAYER_LOGIN'); eq(calls, 1)
    FAKE.Fire('PLAYER_LOGIN'); eq(calls, 1)
    ns.OnLogin(function() calls = calls + 10 end); eq(calls, 11)
end)
